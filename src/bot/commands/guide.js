const { smartReply, cb } = require('../../core/helpers');

module.exports = function registerGuide(bot) {
  bot.command('guide', async (ctx) => { await showGuide(ctx); });
  bot.action(/^guide\|(\d+)$/, async (ctx) => { await ctx.answerCbQuery(); await showGuide(ctx); });
  bot.action(/^guide_page\|(\d+)\|(\d+)$/, async (ctx) => {
    await ctx.answerCbQuery();
    await showGuide(ctx, parseInt(ctx.match[1]));
  });

  async function showGuide(ctx, page = 1) {
    const uid = ctx.from.id;
    const pages = {
      1: { t: '🎮 شروع بازی', c:
        `⚔️ *به EPWR خوش اومدی!*\n\n` +
        `1️⃣ از  فروشگاه یه قهرمان بخر\n` +
        `2️⃣ برو ️ نبرد و سرزمین NPC رو فتح کن\n` +
        `3️⃣ سکه و XP بگیر و قوی‌تر شو\n\n` +
        `💡 هر برد = XP + سکه | هر باخت = آسیب به قهرمان` },
      2: { t: '🍖 غذا و گرسنگی', c:
        `🍖 *هر قهرمان روزانه ۱۰ غذا می‌خوره*\n\n` +
        `⚠️ اگه غذا نباشه: آسیب می‌بینن و می‌میرن!\n` +
        `🔔 اعلان گرسنگی برات میاد\n\n` +
        `✅ راه‌های غذا:\n` +
        `• 🍳 آشپزخانه: ۲۰ غذا/روز هر سطح\n` +
        `• 🍞 خوردن نان: +۱۰۰ غذا\n` +
        `• خرید بسته غذا از فروشگاه/بازار` },
      3: { t: '🏗️ ساختمان‌ها', c:
        `🏰 قلعه: +۲۰ قدرت دفاع/سطح\n` +
        `🧱 دیوار: +۳۰ دفاع/سطح\n` +
        `🗼 برج دیدبانی: +۲۵ دفاع/سطح\n` +
        `🏹 برج کمانداران: +۱۰ حمله/سطح\n` +
        `⚒️ آهنگری: +۱۵ حمله/سطح\n` +
        `🌾 مزرعه: +۵۰ ظرفیت غذا و ۵ گندم/روز\n` +
        `⚔️ پادگان: +۲ ظرفیت قهرمان\n` +
        `🍳 آشپزخانه: ۲۰ غذا/روز\n` +
        `🐔 مرغداری: ۵ تخم مرغ/روز\n\n` +
        `💡 ارتقا: هر سطح ۵۰٪ گرون‌تر` },
      4: { t: '📦 منابع و بازار', c:
        `🪵⚙️ مصالح: فروشگاه یا 🏪 بازار\n` +
        `🌾 گندم: از مزرعه\n\n` +
        `🍞 *زنجیره تولید:*\n` +
        `۱۰ گندم → ۵ آرد → ۵ نان\n` +
        `نان رو بفروش (گرون‌تره!) یا بخور (+۱۰۰🍖)\n\n` +
        `🏪 *بازار:* مصالح و قهرمان رو با قیمت دلخواه بفروش!` },
      5: { t: '⚔️ نبرد و قهرمان', c:
        `🤖 NPC: فتح سرزمین‌ها\n` +
        `👥 PvP: حمله به بازیکن‌ها (رد شدن = هزینه)\n\n` +
        `🛡/⚔️ حالت قهرمان: دفاعی‌ها از قلمرو دفاع می‌کنن، حمله‌ای‌ها به جنگ میرن\n\n` +
        `🪖 *سربازها (قدرت):*\n` +
        `🛡 نیزه‌دار +۲ (۳۰) | 🏹 کماندار +۳ (۵۰💰)\n` +
        `🐴 شوالیه +۵ (۱۰۰💰) | 🎯 منجنیق +۸ (۲۰۰💰)\n\n` +
        `🎭 *اسکین (۵۰💎):* طلایی +۵ دفاع | یخی +۱۰ سلامتی | آتشین +۵ حمله\n` +
        `⚒️ *سلاح (آهن):* شمشیر +۱۰ | نیزه +۸ | تبر +۱۵ | کمان +۱۲\n` +
        `🔄 تبدیل سواره‌نظام: شوالیه سیاه / سواره کماندار (۱۰۰💎)` },
      6: { t: '🤝 اتحاد', c:
        `💰 *خزانه یعنی قدرت:*\n` +
        `• 🎁 جایزه روزانه اعضا: سطح۲=۲۰ تا سطح۵=۱۰۰ سکه\n` +
        `• ⚔️ بونوس جنگ: +۱ قدرت به ازای هر ۱۰۰ سکه خزانه\n` +
        `• ⬆️ ارتقا اتحاد: سطح×۵۰۰ سکه از خزانه\n\n` +
        `⚡ قدرت جنگ اتحاد: ۱۰۰/۱۵۰/۲۲۰/۳۰۰/۴۰۰\n` +
        `👥 ظرفیت: ۱۰/۱۵/۲۰/۲۵/۳۰ عضو\n\n` +
        `🎏 گروه‌های تلگرام خودکار اتحاد می‌سازن!` }
    };

    const p = pages[page] || pages[1];
    const msg = `📚 *راهنما - ${p.t}* (${page}/6)\n\n${p.c}`;

    const navRow = [];
    if (page > 1) navRow.push({ text: '◀️ قبلی', callback_data: `guide_page|${page - 1}|${uid}` });
    navRow.push({ text: `${page}/6`, callback_data: `guide_page|${page}|${uid}` });
    if (page < 6) navRow.push({ text: 'بعدی ▶️', callback_data: `guide_page|${page + 1}|${uid}` });

    await smartReply(ctx, msg, { parse_mode: 'Markdown', reply_markup: { inline_keyboard: [
      navRow,
      [{ text: '🔙 بازگشت', callback_data: cb('mainmenu', uid) }]
    ] } });
  }
};